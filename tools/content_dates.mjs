// STICKY-1: keep worker/src/content-dates.gen.js complete. Append-only: an id already dated keeps its date; a new id gets the date of the commit that
// first added it (git history), or now when it is not committed yet. Run `node tools/content_dates.mjs`; test/content-feed.test.js fails when an id is missing.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { SOLUTIONS } from '../worker/src/solutions.js';
import { SYNTHESES } from '../worker/src/syntheses-data.js';
const FILE = new URL('../worker/src/content-dates.gen.js', import.meta.url);
let DATES = {};
try { DATES = (await import(FILE.href + '?t=' + Date.now())).DATES; } catch (e) { DATES = {}; }  // allow-silent: first run, no file yet
const files = ['worker/src/solutions.js', 'worker/src/more-solutions.js', 'worker/src/syntheses-data.js'];
const firstAdded = id => {
  const bare = id.split(':')[1];
  const out = execFileSync('git', ['log', '-S' + `id: '${bare}'`, '--format=%aI', '--reverse', '--', ...files], { encoding: 'utf8' }).trim().split('\n').filter(Boolean);
  return out[0] || new Date().toISOString();
};
const ids = [...SOLUTIONS.map(s => 'solution:' + s.id), ...SYNTHESES.map(s => 'synthesis:' + s.id)];
let added = 0;
for (const id of ids) if (!DATES[id]) { DATES[id] = firstAdded(id); added++; }
const sorted = Object.fromEntries(Object.entries(DATES).sort(([a], [b]) => (a < b ? -1 : 1)));
writeFileSync(FILE, `// GENERATED by tools/content_dates.mjs (append-only). Do not edit.\nexport const DATES = ${JSON.stringify(sorted, null, 1)};\n`);
console.log(`content dates: ${ids.length} entries, ${added} added`);

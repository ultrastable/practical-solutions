// BEHAVIOUR-SOURCES-1: every behavioural citation is looked up in OpenAlex by title, year (within one) and first-author surname. A match is `verified`;
// no match is `unresolved`; books and reports are `not_indexed` (shown as not machine-checked). The result goes to ledger/behaviour-sources.json and the
// module the Worker reads (worker/src/behaviour-sources.gen.js). An unresolved source is flagged on every page that cites it and caps the strength of a
// lever whose sources are all unresolved. A lookup that fails (network, rate limit) leaves the previous status; it never turns into verified.
//   node tools/behaviour_sources.mjs [--check]     --check fails when the generated module is stale or any source is unresolved
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { CHECKS } from '../worker/src/behaviour-lib.js';

export const LEDGER = 'ledger/behaviour-sources.json', GEN = 'worker/src/behaviour-sources.gen.js';
const HEAD = '// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.\n// Generated by tools/behaviour_sources.mjs from ledger/behaviour-sources.json. Do not edit.\n';
const norm = t => String(t).toLowerCase().replace(/<[^>]+>/g, '').replace(/[^a-z0-9 ]+/g, ' ').split(/\s+/).filter(w => w.length > 2);
export const similar = (a, b) => { const x = new Set(norm(a)), y = new Set(norm(b)); if (!x.size || !y.size) return 0; const i = [...x].filter(w => y.has(w)).length; return i / Math.max(x.size, y.size); };
export function matches(work, [title, year, surname]) {
  const names = (work.authorships || []).map(a => String((a.author || {}).display_name || '').toLowerCase());
  return similar(work.title || work.display_name || '', title) >= 0.8 && Math.abs((work.publication_year || 0) - year) <= 1 && names.some(n => n.includes(surname.toLowerCase().replace('-', ' ')) || n.includes(surname.toLowerCase()));
}
export async function checkAll({ fetch: f = globalThis.fetch, prev = {}, now = () => Date.now(), checks = CHECKS } = {}) {
  const out = {};
  for (const [id, c] of Object.entries(checks)) {
    if (c.length === 1) { out[id] = { status: 'not_indexed', kind: c[0] }; continue; }
    const [title, year] = c;
    try {
      const u = 'https://api.openalex.org/works?per-page=5&select=title,publication_year,doi,authorships&filter=' + encodeURIComponent(`title.search:${norm(title).slice(0, 12).join(' ')},publication_year:${year - 1}-${year + 1}`);
      const r = await f(u, { headers: { accept: 'application/json', 'user-agent': 'practical-solutions citation check (public)' } });
      if (!r.ok) { out[id] = prev[id] || { status: 'unchecked', note: 'HTTP ' + r.status }; continue; }
      let hit = ((await r.json()).results || []).find(w => matches(w, c));
      if (!hit) {   // second route: relevance search on the whole title, no year filter; the year and author are still checked on the result
        const r2 = await f('https://api.openalex.org/works?per-page=10&select=title,publication_year,doi,authorships&search=' + encodeURIComponent(title), { headers: { accept: 'application/json', 'user-agent': 'practical-solutions citation check (public)' } });
        if (r2.ok) hit = ((await r2.json()).results || []).find(w => matches(w, c));
      }
      out[id] = hit ? { status: 'verified', doi: hit.doi || null, at: new Date(now()).toISOString() } : { status: 'unresolved', at: new Date(now()).toISOString() };
    } catch (e) { out[id] = prev[id] || { status: 'unchecked', note: String(e.message || e).slice(0, 80) }; }
  }
  return { schema: 'ps-behaviour-sources/1', at: new Date(now()).toISOString(), results: out };
}
export const generated = led => HEAD + 'export const CHECKED = ' + JSON.stringify({ at: led.at || null, status: Object.fromEntries(Object.entries(led.results || {}).map(([k, v]) => [k, v.status])) }, null, 1) + ';\n';
if (import.meta.url === `file://${process.argv[1]}`) {
  const prev = existsSync(LEDGER) ? JSON.parse(readFileSync(LEDGER, 'utf8')) : { results: {} };
  if (process.argv.includes('--check')) {
    const bad = Object.entries(prev.results || {}).filter(([, v]) => v.status === 'unresolved').map(([k]) => k);
    const stale = !existsSync(GEN) || readFileSync(GEN, 'utf8') !== generated(prev);
    console.log(JSON.stringify({ unresolved: bad, stale_module: stale }));
    process.exit(bad.length || stale ? 1 : 0);
  }
  const led = await checkAll({ prev: prev.results || {} });
  writeFileSync(LEDGER, JSON.stringify(led, null, 1) + '\n'); writeFileSync(GEN, generated(led));
  const c = {}; for (const v of Object.values(led.results)) c[v.status] = (c[v.status] || 0) + 1;
  console.log(JSON.stringify({ counts: c, unresolved: Object.entries(led.results).filter(([, v]) => v.status === 'unresolved').map(([k]) => k) }));
}

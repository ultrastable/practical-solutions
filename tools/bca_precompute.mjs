// Writes worker/src/bca-precomputed.gen.js: the benefit-cost result of every seed model (CPU-LIMIT-1). Usage: node tools/bca_precompute.mjs [--check]
import { writeFileSync, readFileSync } from 'node:fs';
import { MODELS } from '../worker/src/bca-models.js';
import { computeSeed } from '../worker/src/bca.js';
const out = new URL('../worker/src/bca-precomputed.gen.js', import.meta.url);
const body = `// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0
// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.
// GENERATED by tools/bca_precompute.mjs from bca-models.js. Do not edit. test/cpu_budget.test.js fails when it is stale.
export const PRECOMPUTED = ${JSON.stringify(Object.fromEntries(Object.keys(MODELS).map(id => [id, computeSeed(id)])))};
`;
if (process.argv.includes('--check')) { if (readFileSync(out, 'utf8') !== body) { console.error('bca-precomputed.gen.js is stale: run node tools/bca_precompute.mjs'); process.exit(1); } } else writeFileSync(out, body);

// ASK-1: builds the retrieval index the Worker ships (worker/src/ask-index.gen.js) from the site's own data. Runs in every workflow that changes the
// catalogue; `--check` fails when the committed index is stale.   node tools/askindex.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { buildIndex } from '../vendor/ultrastable/core/ask/index.js';
import { buildCatalog } from '../worker/src/catalog.js';
import { SOLUTIONS } from '../worker/src/solutions.js';
import { askDocs } from '../worker/src/ask-docs.js';

export const GEN = 'worker/src/ask-index.gen.js';
export function generated() {
  const index = buildIndex(askDocs(buildCatalog({ problems: null, solutions: SOLUTIONS })), { snippet: 420 });
  return `// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.\n// GENERATED by tools/askindex.mjs from the catalogue. Do not edit.\nexport const ASK_INDEX = ${JSON.stringify(index)};\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const g = generated();
  if (process.argv.includes('--check')) { if (!existsSync(GEN) || readFileSync(GEN, 'utf8') !== g) { console.error(GEN + ' is stale: run node tools/askindex.mjs'); process.exit(1); } console.log('ask index ok'); }
  else { writeFileSync(GEN, g); console.log(JSON.stringify({ docs: (g.match(/"id":/g) || []).length, bytes: g.length })); }
}

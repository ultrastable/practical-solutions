// PIPELINE-1: reads every ledger the loops write, counts each stage, assigns an advocate to each queued problem, records the run in the history,
// and writes ledger/pipeline.json plus worker/src/pipeline.gen.js (what /pipeline and /pipeline.json show). `--check` is the stall probe: it exits 1
// when substantive movement over the window is below the floor, and prints why.
//   node tools/pipeline.mjs [--check] [--no-write]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { PROBLEMS } from '../worker/src/problems.js';
import { SOLUTIONS } from '../worker/src/solutions.js';
import { PRECOMPUTED } from '../worker/src/bca-precomputed.gen.js';
import { SCAN } from '../worker/src/problem-scan.gen.js';
import { solvedSet, selectQueue, counts, record, health, pass, STAGES, RULES } from '../ps/pipeline.js';

export const FILES = { ledger: 'ledger/pipeline.json', gen: 'worker/src/pipeline.gen.js', scan: 'ledger/problem-scan.json', connections: 'ledger/connections.json', evidence: 'ledger/evidence-leads.json', redteam: 'ledger/redteam.json', verified: 'ledger/syntheses-verified.json', discovered: 'ledger/synth-discovered.json' };
const readJson = (f, d) => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : d);
const HEADER = '// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.\n// GENERATED by tools/pipeline.mjs from ledger/pipeline.json. Do not edit.\n';

export function build({ prev = {}, now = Date.now(), scan = readJson(FILES.scan, SCAN), connections = readJson(FILES.connections, null), evidence = readJson(FILES.evidence, null), redteam = readJson(FILES.redteam, null), verified = readJson(FILES.verified, null), discovered = readJson(FILES.discovered, null), solutions = SOLUTIONS, problems = PROBLEMS, bca = PRECOMPUTED, source = 'run' } = {}) {
  const solved = solvedSet({ problems, scan, solutions });
  const q = selectQueue({ scan, solved, connections, evidence: evidence || { items: {} }, prev: { queue: prev.queue, cooldown: prev.cooldown }, now });
  const c = counts({ problems, scan, solutions, solved, queue: q.queue, evidence, connections, redteam, verifiedSyntheses: verified, discovered, bca });
  const history = record(prev.history || [], c, now, RULES, source);
  return { schema: 'ps-pipeline/1', at: new Date(now).toISOString(), rules: RULES, counts: c, queue: q.queue, cooldown: q.cooldown, log: [...(prev.log || []), ...q.log.map(x => ({ at: new Date(now).toISOString(), ...x }))].slice(-80), history, health: health(history, now) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const prev = readJson(FILES.ledger, {}), check = process.argv.includes('--check');
  const out = build({ prev });
  if (!process.argv.includes('--no-write')) {
    writeFileSync(FILES.ledger, JSON.stringify(out, null, 1) + '\n');
    writeFileSync(FILES.gen, HEADER + 'export const PIPELINE = ' + JSON.stringify({ at: out.at, rules: out.rules, stages: STAGES, counts: out.counts, queue: out.queue, log: out.log.slice(-20), history: out.history.slice(-40), health: out.health }) + ';\n');
  }
  console.log(JSON.stringify({ counts: out.counts, queue: out.queue.length, health: out.health }, null, 1));
  if (check && !pass(out.health)) { console.error('PIPELINE STALLED: ' + out.health.reasons.join('; ')); process.exit(1); }
}

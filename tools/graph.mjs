// KNOWLEDGE-GRAPH-1 (tenant side), on core/datagraph (DATAGRAPH-1): hands this catalogue's records to the core graph engine, which measures hubs, communities,
// bridges and orphans and predicts missing links. The record mapping is tenant data; the graph logic is core. Semantic leads from tools/connections.mjs
// (core/discover) enter as proposed edges: leads, never facts. Near-duplicate merging was dropped with core/knowledge (the catalogue has no duplicate ids).
// Outputs: ledger/graph.json (compact summary, the diff base for the next run), worker/src/graph-insights.gen.js (insights shown in /changes and the feed).
//   node tools/graph.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { run } from '../worker/src/graph-run.js';
export { records, run } from '../worker/src/graph-run.js';
export const FILES = { snap: 'ledger/graph.json', gen: 'worker/src/graph-insights.gen.js', conn: 'ledger/connections.json' };
const readJson = (f, d) => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : d);

// records: nodes (kind, id, title, entities) and the facts between them (refs: from -> to).
const header = by => `// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.\n// GENERATED by ${by}. Do not edit.\n`;

export async function main() {
  const prev = readJson(FILES.snap, null), now = new Date().toISOString();
  const r = run({ prev, conn: readJson(FILES.conn, { candidates: [] }), now });
  // an unchanged graph writes nothing, so the run is not a commit and not a "change"
  if (prev && JSON.stringify({ ...prev, at: 0 }) === JSON.stringify({ ...r.snapshot, at: 0 })) return { ...r, written: false };
  writeFileSync(FILES.snap, JSON.stringify(r.snapshot));
  writeFileSync(FILES.gen, header('tools/graph.mjs') + `export const GRAPH_INSIGHTS = ${JSON.stringify({ at: now, stats: r.stats, insights: r.insights, leads: r.leads })};\n`);
  return { ...r, written: true };
}
if (import.meta.url === `file://${process.argv[1]}`) main().then(r => console.log(JSON.stringify({ stats: r.stats, insights: r.insights.length, written: r.written }))).catch(e => { console.error(e); process.exit(1); });

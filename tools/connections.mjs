const digits = s => (String(s).match(/\d[\d.,]*/g) || []).map(x => x.replace(/[.,]+$/, ''));
export function checkRationale(text, sources) {
  const t = String(text || '').replace(/\s+/g, ' ').trim();
  if (t.length < 40 || t.length > 600 || /NO_ANSWER/.test(t)) return null;
  const hay = sources.join(' ');
  return digits(t).every(d => hay.includes(d)) ? t : null;
}

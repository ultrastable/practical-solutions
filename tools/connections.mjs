// ---- one run -------------------------------------------------------------------------------------------------------------------------
export async function run({ embed = null, ask = null, now = Date.now(), maxEmbed = 3000, cache = readJson(FILES.cache, {}), ledger = readJson(FILES.ledger, null), input = corpus(), askDocs = ASK_INDEX.docs, modelCalls = 20 } = {}) {
  const at = new Date(now).toISOString(), errors = [];
  const noEmbed = async () => { throw new Error('embedding skipped (offline)'); };
  const g = await D.refreshEmbeddings({ nodes: input.nodes, cache: cache.graph || {}, embed: embed || noEmbed, model: EMBED_MODEL, max: maxEmbed });
  const a = await D.refreshEmbeddings({ nodes: askDocs.map(d => ({ id: d.id, label: d.title, text: d.text })), cache: cache.ask || {}, embed: embed || noEmbed, model: EMBED_MODEL, max: Math.max(0, maxEmbed - g.embedded) });
  errors.push(...g.errors.map(e => ({ step: 'embed-graph', ...e })), ...a.errors.map(e => ({ step: 'embed-ask', ...e })));
  // no vectors at all (the model route is down and nothing is cached): record nothing, tune nothing, publish nothing; the run reports failure
  if (!Object.keys(g.cache.rows || {}).length) return { at, errors, run: null, embedded: 0, pending: g.pending, cache: { graph: g.cache, ask: a.cache }, ledger, view: null, askPacked: null, skipped: true };
  const M = D.unpack(D.packCache(g.cache));
  const prior = ledger || { v: 1, runs: [], entries: {}, retired: {}, params: { pct: D.DEFAULTS.pct }, decisions: [] };
  const params = { ...(prior.params || { pct: D.DEFAULTS.pct }) };
  const result = D.discover({ nodes: input.nodes, edges: input.edges, M, params, known: input.known });
  const merged = D.mergeLedger(prior, result, { now, edges: input.edges, known: input.known });
  const L = merged.ledger; L.params = params; L.decisions = [...(prior.decisions || [])];
  // score the last change against this run, then decide the next one
  const pending = L.decisions.slice().reverse().find(d => d.kept == null);
  const scored = pending ? D.scorePrediction(pending, merged.run) : null;
  if (scored) L.decisions = L.decisions.map(d => (d === pending ? scored : d));
  const t = D.tune(L, params);
  if (t.decision) { L.params = t.params; L.decisions = [...L.decisions, t.decision].slice(-50); }
  // JUSTIFY-1: drop what cannot say why, originate what the rules justify, then let a model panel veto (bounded; failures leave the code's verdict)
  const nodes = new Map(input.nodes.map(n => [n.id, n]));
  const sc = screen(L, input, { now });
  const pr = ask && modelCalls > 0 ? await panelReview(L, nodes, ask, { max: modelCalls, now }) : { reviewed: 0, errors: [] };
  errors.push(...pr.errors);
  merged.run.open = L.totals.open; merged.run.dropped += sc.dropped;
  const v = view({ result, ledger: L, nodes, url: input.url, decision: t.decision, scored, at });
  return { at, errors, run: merged.run, embedded: g.embedded + a.embedded, pending: g.pending + a.pending, cache: { graph: g.cache, ask: a.cache }, ledger: L, view: v, askPacked: D.packCache(a.cache, askDocs.map(d => d.id)), links: buildLinks({ nodes: input.nodes, M, ledger: L, url: input.url, at }) };
}

export function write(r) {
  if (r.skipped) return; // nothing was learned, so nothing is rewritten
  // one vector per line, so a run that changes ten items changes ten lines of history
  const rows = c => '{\n' + Object.entries(c.rows || {}).sort(([x], [y]) => x.localeCompare(y)).map(([id, x]) => JSON.stringify(id) + ':' + JSON.stringify(x)).join(',\n') + '\n}';
  writeFileSync(FILES.cache, `{"schema":"ps-embeddings/1","graph":{"model":${JSON.stringify(r.cache.graph.model)},"dim":${r.cache.graph.dim},"rows":${rows(r.cache.graph)}},\n"ask":{"model":${JSON.stringify(r.cache.ask.model)},"dim":${r.cache.ask.dim},"rows":${rows(r.cache.ask)}}}\n`);
  writeFileSync(FILES.ledger, JSON.stringify({ schema: 'ps-connections/1', ...r.ledger }, null, 1) + '\n');
  writeFileSync(FILES.gen, HEADER('tools/connections.mjs from ledger/connections.json') + 'export const CONNECTIONS = ' + JSON.stringify(r.view) + ';\n');
  writeFileSync(FILES.links, linksText(r.links));
  writeFileSync(FILES.ask, HEADER('tools/connections.mjs from ledger/embeddings.json') + `export const ASK_VECTORS = ${JSON.stringify({ model: EMBED_MODEL, ...r.askPacked })};\n`);
}

// Rebuilds only the link graph from the cached vectors and the ledger: no model call, so it needs no network and no credential.
export function linksOnly({ cache = readJson(FILES.cache, {}), ledger = readJson(FILES.ledger, null), input = corpus(), now = Date.now() } = {}) {
  const M = D.unpack(D.packCache(cache.graph));
  return buildLinks({ nodes: input.nodes, M, ledger, url: input.url, at: (ledger && ledger.runs && ledger.runs.length ? ledger.runs[ledger.runs.length - 1].at : new Date(now).toISOString()) });
}


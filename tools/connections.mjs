// ---- the catalogue as a graph ----------------------------------------------------------------------------------------------------------
export function corpus({ problems = PROBLEMS, solutions = SOLUTIONS, scan = SCAN, syntheses = SYNTHESES, discovered = readJson(FILES.synth, { entries: [] }).entries || [] } = {}) {
  const byInd = new Map(problems.map(p => [p.ind, p.id])), alias = new Map(), nodes = [], url = new Map();
  const noteOf = new Map((scan.entries || []).filter(e => byInd.has(e.code)).map(e => [byInd.get(e.code), e.note])); // the source's own definition
  for (const p of problems) { nodes.push({ id: 'p:' + p.id, kind: 'problem', domain: p.domain, label: p.title, text: [p.domain, p.unit, p.target_src, noteOf.get(p.id)].filter(Boolean).join('. ').slice(0, 800), props: { weight: 1.5 } }); url.set('p:' + p.id, '/problems/' + p.id); }
  for (const e of scan.entries || []) {
    if (byInd.has(e.code)) { alias.set(e.id, byInd.get(e.code)); continue; } // the same indicator as a hand-checked problem: one node, not two
    const pace = e.m && e.m.pace != null ? Math.min(2, 1 + Math.abs(Number(e.m.pace)) / 10) : 1;
    nodes.push({ id: 'p:' + e.id, kind: 'problem', domain: e.domain, label: e.title, text: String(e.note || '').slice(0, 600), props: { weight: pace } }); url.set('p:' + e.id, '/catalogue/' + e.id);
  }
  const pid = id => 'p:' + (alias.get(id) || id), dom = new Map(nodes.map(n => [n.id, n.domain])), edges = [];
  for (const s of solutions) {
    const ps = (s.problem_ids || []).map(pid).filter(id => dom.has(id));
    const ev = (s.evidence || []).map(x => x.finding).filter(Boolean).join(' ');
    nodes.push({ id: 's:' + s.id, kind: 'solution', domain: dom.get(ps[0]) || s.problem || '', label: s.title, text: [s.claim, ev].filter(Boolean).join(' ').slice(0, 1200) }); url.set('s:' + s.id, '/solutions/' + s.id);
    for (const p of ps) edges.push({ src: 's:' + s.id, rel: 'addresses', dst: p });
  }
  const known = [...syntheses, ...discovered].map(x => (x.components || []).map(c => 's:' + c)).filter(c => c.length >= 2);
  return { nodes, edges, known, url };
}

// ---- embeddings through the tenant's keyless model route (an Actions run proves itself with its OIDC token) ------------------------------
export const embedVia = ({ fetch: f = globalThis.fetch, secrets = process.env } = {}) => async texts => {
  if (!(secrets.PS_LLM_URL && secrets.ACTIONS_ID_TOKEN_REQUEST_URL && secrets.ACTIONS_ID_TOKEN_REQUEST_TOKEN)) throw new Error('no OIDC model route in this environment');
  const t = await f(`${secrets.ACTIONS_ID_TOKEN_REQUEST_URL}&audience=practical-solutions-llm`, { headers: { authorization: `Bearer ${secrets.ACTIONS_ID_TOKEN_REQUEST_TOKEN}` } });
  if (!t.ok) throw new Error('oidc token ' + t.status);
  const { value } = await t.json();
  const r = await f(secrets.PS_LLM_URL.replace(/\/$/, '') + '/embed', { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${value}` }, body: JSON.stringify({ texts, model: EMBED_MODEL }) });
  const j = await r.json().catch(() => ({}));
  if (!r.ok || !Array.isArray(j.vectors)) throw new Error('embed ' + r.status + ' ' + (j.error || '') + ' ' + (j.detail || ''));
  return j.vectors;
};


// DISCOVER-1 for this catalogue: every problem (the hand-checked ones and the ones the problem scan found in public statistics), every
// solution and every combination already made become one knowledge graph with a vector index (core/discover). Each run embeds only what
// changed, finds connections nobody has drawn (a solution proven on one problem for a similar problem it was never tried on, two solutions
// worth combining, alike items with no link, problems no solution comes near), screens them for novelty, settles earlier ones against what
// the catalogue later adopted, and tunes its own threshold. Code ranks; a model only words the top few, and that text is labelled.
//   node tools/connections.mjs [--offline] [--no-model] [--max-embed 3000]
// Outputs: ledger/embeddings.json (int8 vector cache), ledger/connections.json (the ledger), worker/src/connections.gen.js (what the
// site shows), worker/src/ask-vectors.gen.js (vectors for /ask).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import * as D from '../vendor/ultrastable/core/discover/index.js';
import { PROBLEMS } from '../worker/src/problems.js';
import { SOLUTIONS } from '../worker/src/solutions.js';
import { SCAN } from '../worker/src/problem-scan.gen.js';
import { SYNTHESES } from '../worker/src/syntheses-data.js';
import { ASK_INDEX } from '../worker/src/ask-index.gen.js';
import { complete } from '../ps/llm.js';

export const EMBED_MODEL = '@cf/baai/bge-small-en-v1.5';
export const FILES = { cache: 'ledger/embeddings.json', ledger: 'ledger/connections.json', gen: 'worker/src/connections.gen.js', ask: 'worker/src/ask-vectors.gen.js', synth: 'ledger/synth-discovered.json' };
const readJson = (f, d) => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : d);
const HEADER = by => `// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.\n// GENERATED by ${by}. Do not edit.\n`;

// ---- the catalogue as a graph ----------------------------------------------------------------------------------------------------------
export function corpus({ problems = PROBLEMS, solutions = SOLUTIONS, scan = SCAN, syntheses = SYNTHESES, discovered = readJson(FILES.synth, { entries: [] }).entries || [] } = {}) {
  const byInd = new Map(problems.map(p => [p.ind, p.id])), alias = new Map(), nodes = [], url = new Map();
  const noteOf = new Map((scan.entries || []).filter(e => byInd.has(e.code)).map(e => [byInd.get(e.code), e.note])); // the source's own definition
  for (const p of problems) { nodes.push({ id: 'p:' + p.id, kind: 'problem', domain: p.domain, label: p.title, text: [p.domain, p.unit, p.target_src, noteOf.get(p.id)].filter(Boolean).join('. ').slice(0, 800), props: { weight: 1.5 } }); url.set('p:' + p.id, '/problems/' + p.id); }
  for (const e of scan.entries || []) {
    if (byInd.has(e.code)) { alias.set(e.id, byInd.get(e.code)); continue; } // the same indicator as a hand-checked problem: one node, not two
    const pace = e.m && e.m.pace != null ? Math.min(2, 1 + Math.abs(Number(e.m.pace)) / 10) : 1;
    nodes.push({ id: 'p:' + e.id, kind: 'problem', domain: e.domain, label: e.title, text: String(e.note || '').slice(0, 600), props: { weight: pace } }); url.set('p:' + e.id, '/catalogue/' + e.id);
  }
  const pid = id => 'p:' + (alias.get(id) || id), dom = new Map(nodes.map(n => [n.id, n.domain])), edges = [];
  for (const s of solutions) {
    const ps = (s.problem_ids || []).map(pid).filter(id => dom.has(id));
    const ev = (s.evidence || []).map(x => x.finding).filter(Boolean).join(' ');
    nodes.push({ id: 's:' + s.id, kind: 'solution', domain: dom.get(ps[0]) || s.problem || '', label: s.title, text: [s.claim, ev].filter(Boolean).join(' ').slice(0, 1200) }); url.set('s:' + s.id, '/solutions/' + s.id);
    for (const p of ps) edges.push({ src: 's:' + s.id, rel: 'addresses', dst: p });
  }
  const known = [...syntheses, ...discovered].map(x => (x.components || []).map(c => 's:' + c)).filter(c => c.length >= 2);
  return { nodes, edges, known, url };
}

// ---- embeddings through the tenant's keyless model route (an Actions run proves itself with its OIDC token) ------------------------------
export const embedVia = ({ fetch: f = globalThis.fetch, secrets = process.env } = {}) => async texts => {
  if (!(secrets.PS_LLM_URL && secrets.ACTIONS_ID_TOKEN_REQUEST_URL && secrets.ACTIONS_ID_TOKEN_REQUEST_TOKEN)) throw new Error('no OIDC model route in this environment');
  const t = await f(`${secrets.ACTIONS_ID_TOKEN_REQUEST_URL}&audience=practical-solutions-llm`, { headers: { authorization: `Bearer ${secrets.ACTIONS_ID_TOKEN_REQUEST_TOKEN}` } });
  if (!t.ok) throw new Error('oidc token ' + t.status);
  const { value } = await t.json();
  const r = await f(secrets.PS_LLM_URL.replace(/\/$/, '') + '/embed', { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${value}` }, body: JSON.stringify({ texts, model: EMBED_MODEL }) });
  const j = await r.json().catch(() => ({}));
  if (!r.ok || !Array.isArray(j.vectors)) throw new Error('embed ' + r.status + ' ' + (j.error || '') + ' ' + (j.detail || ''));
  return j.vectors;
};

// ---- a model words the top few new connections; code checks it invents no figure and keeps it short --------------------------------------
const digits = s => (String(s).match(/\d[\d.,]*/g) || []).map(x => x.replace(/[.,]+$/, ''));
export function checkRationale(text, sources) {
  const t = String(text || '').replace(/\s+/g, ' ').trim();
  if (t.length < 40 || t.length > 600 || /NO_ANSWER/.test(t)) return null;
  const hay = sources.join(' ');
  return digits(t).every(d => hay.includes(d)) ? t : null;
}
const rationalePrompt = (c, nodes) => `Two items from a catalogue of practical solutions to global problems:\n${c.members.concat(c.via && !String(c.via).includes(' ~ ') ? [c.via] : []).map(id => { const n = nodes.get(id); return n ? `- ${n.kind} "${n.label}": ${String(n.text || '').slice(0, 500)}` : ''; }).join('\n')}\n\nIn at most three sentences, say through which mechanism ${c.type === 'transfer' ? `the solution "${nodes.get(c.members[0]).label}" might also reduce "${nodes.get(c.members[1]).label}"` : `"${nodes.get(c.members[0]).label}" and "${nodes.get(c.members[1]).label}" might work better together`}, and what a cheap first test would measure. Use only the text above; do not quote any figure that is not in it. If there is no plausible mechanism, reply NO_ANSWER.`;

// ---- the site's view: small, labelled, linked --------------------------------------------------------------------------------------------
export function view({ result, ledger, nodes, url, decision, scored, at }) {
  const label = id => (nodes.get(id) || {}).label || id;
  const show = e => ({ id: e.id, type: e.type, status: e.status, novelty: e.novelty, score: e.score, cross: e.cross, first_seen: e.first_seen,
    members: e.members.map(id => ({ id, label: label(id), kind: (nodes.get(id) || {}).kind, domain: (nodes.get(id) || {}).domain, url: url.get(id) || null })),
    via: e.via && !String(e.via).includes(' ~ ') ? { id: e.via, label: label(e.via), url: url.get(e.via) || null } : null,
    why: D.explain(e, label), why_model: e.why_model || null });
  const entries = Object.values(ledger.entries);
  const open = entries.filter(e => e.status === 'new' || e.status === 'standing').sort((a, b) => b.score - a.score);
  const byType = t => open.filter(e => e.type === t).slice(0, 12).map(show);
  const sizes = Object.entries(result.community_sizes).sort((a, b) => b[1] - a[1]).slice(0, 8)
    .map(([c, n]) => ({ size: n, sample: Object.entries(result.communities).filter(([, x]) => x === c).map(([id]) => id).filter(id => nodes.get(id)).slice(0, 4).map(id => ({ label: label(id), url: url.get(id) || null })) }));
  return {
    at, model: EMBED_MODEL, tau: result.tau, stats: result.stats, totals: ledger.totals, params: ledger.params,
    transfer: byType('transfer'), combination: byType('combination'), bridge: byType('bridge'), frontier: byType('frontier'),
    confirmed: entries.filter(e => e.status === 'confirmed').sort((a, b) => String(b.settled).localeCompare(String(a.settled))).slice(0, 8).map(show),
    hubs: result.hubs.slice(0, 8).map(h => ({ label: label(h.id), url: url.get(h.id) || null, reach: h.reach })),
    communities: sizes, runs: ledger.runs.slice(-30), decisions: (ledger.decisions || []).slice(-10), scored: scored || null, decision: decision || null,
  };
}

// ---- one run -------------------------------------------------------------------------------------------------------------------------
export async function run({ embed = null, ask = null, now = Date.now(), maxEmbed = 3000, cache = readJson(FILES.cache, {}), ledger = readJson(FILES.ledger, null), input = corpus(), askDocs = ASK_INDEX.docs, modelCalls = 3 } = {}) {
  const at = new Date(now).toISOString(), errors = [];
  const noEmbed = async () => { throw new Error('embedding skipped (offline)'); };
  const g = await D.refreshEmbeddings({ nodes: input.nodes, cache: cache.graph || {}, embed: embed || noEmbed, model: EMBED_MODEL, max: maxEmbed });
  const a = await D.refreshEmbeddings({ nodes: askDocs.map(d => ({ id: d.id, label: d.title, text: d.text })), cache: cache.ask || {}, embed: embed || noEmbed, model: EMBED_MODEL, max: Math.max(0, maxEmbed - g.embedded) });
  errors.push(...g.errors.map(e => ({ step: 'embed-graph', ...e })), ...a.errors.map(e => ({ step: 'embed-ask', ...e })));
  const M = D.unpack(D.packCache(g.cache));
  const prior = ledger || { v: 1, runs: [], entries: {}, retired: {}, params: { pct: D.DEFAULTS.pct }, decisions: [] };
  const params = { ...(prior.params || { pct: D.DEFAULTS.pct }) };
  const result = D.discover({ nodes: input.nodes, edges: input.edges, M, params, known: input.known });
  const merged = D.mergeLedger(prior, result, { now, edges: input.edges, known: input.known });
  const L = merged.ledger; L.params = params; L.decisions = [...(prior.decisions || [])];
  // score the last change against this run, then decide the next one
  const pending = L.decisions.slice().reverse().find(d => d.kept == null);
  const scored = pending ? D.scorePrediction(pending, merged.run) : null;
  if (scored) L.decisions = L.decisions.map(d => (d === pending ? scored : d));
  const t = D.tune(L, params);
  if (t.decision) { L.params = t.params; L.decisions = [...L.decisions, t.decision].slice(-50); }
  // a model words the top new connections (bounded calls; failures and empty replies leave the code's own sentence)
  const nodes = new Map(input.nodes.map(n => [n.id, n]));
  if (ask && modelCalls > 0) {
    const todo = Object.values(L.entries).filter(e => (e.type === 'transfer' || e.type === 'combination') && (e.status === 'new' || e.status === 'standing') && !e.why_model).sort((x, y) => y.score - x.score).slice(0, modelCalls);
    for (const e of todo) {
      try {
        const srcs = e.members.concat(e.via ? [e.via] : []).map(id => nodes.get(id)).filter(Boolean).map(n => n.label + ' ' + (n.text || ''));
        const r = await ask(rationalePrompt(e, nodes));
        const ok = checkRationale(r, srcs);
        L.entries[e.id] = { ...L.entries[e.id], why_model: ok ? { text: ok, at, note: 'Written by a model from the two entries only and checked for invented figures; a hypothesis, not evidence.' } : null, why_model_tried: at };
      } catch (x) { errors.push({ step: 'rationale', id: e.id, error: String(x.message || x).slice(0, 160) }); }
    }
  }
  const v = view({ result, ledger: L, nodes, url: input.url, decision: t.decision, scored, at });
  return { at, errors, run: merged.run, embedded: g.embedded + a.embedded, pending: g.pending + a.pending, cache: { graph: g.cache, ask: a.cache }, ledger: L, view: v, askPacked: D.packCache(a.cache, askDocs.map(d => d.id)) };
}

export function write(r) {
  // one vector per line, so a run that changes ten items changes ten lines of history
  const rows = c => '{\n' + Object.entries(c.rows || {}).sort(([x], [y]) => x.localeCompare(y)).map(([id, x]) => JSON.stringify(id) + ':' + JSON.stringify(x)).join(',\n') + '\n}';
  writeFileSync(FILES.cache, `{"schema":"ps-embeddings/1","graph":{"model":${JSON.stringify(r.cache.graph.model)},"dim":${r.cache.graph.dim},"rows":${rows(r.cache.graph)}},\n"ask":{"model":${JSON.stringify(r.cache.ask.model)},"dim":${r.cache.ask.dim},"rows":${rows(r.cache.ask)}}}\n`);
  writeFileSync(FILES.ledger, JSON.stringify({ schema: 'ps-connections/1', ...r.ledger }, null, 1) + '\n');
  writeFileSync(FILES.gen, HEADER('tools/connections.mjs from ledger/connections.json') + 'export const CONNECTIONS = ' + JSON.stringify(r.view) + ';\n');
  writeFileSync(FILES.ask, HEADER('tools/connections.mjs from ledger/embeddings.json') + `export const ASK_VECTORS = ${JSON.stringify({ model: EMBED_MODEL, ...r.askPacked })};\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = n => process.argv.includes(n), val = (n, d) => { const i = process.argv.indexOf(n); return i > 0 ? Number(process.argv[i + 1]) : d; };
  const embed = arg('--offline') ? null : embedVia();
  const ask = arg('--no-model') || arg('--offline') ? null : async prompt => { const r = await complete({ secrets: process.env, prompt, maxTokens: 300 }); return r.ok ? r.text : ''; };
  const r = await run({ embed, ask, maxEmbed: val('--max-embed', 3000) });
  write(r);
  console.log(JSON.stringify({ at: r.at, embedded: r.embedded, pending: r.pending, run: r.run, totals: r.ledger.totals, tau: r.view.tau, decision: r.view.decision, scored: r.view.scored, errors: r.errors.slice(0, 5) }));
  // an embedding failure with nothing cached is a failed run (the loop must see it); with a cache it degrades and still publishes
  if (r.errors.length && !Object.keys(r.cache.graph.rows || {}).length) process.exitCode = 2;
}
